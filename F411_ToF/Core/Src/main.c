/*
 *  ========= ToF Sensor Routines ==========
 * */
void tofSensorRoutine(uint16_t dev, uint8_t newDev, GPIO_TypeDef* shutPort, uint16_t shutPin) {
	dbg_printf("TOF SENSOR ROUTINE\n");
	uint8_t tofBootState = 0;
	uint8_t Timeout = 0;

	HAL_GPIO_WritePin(shutPort, shutPin, GPIO_PIN_RESET);
	HAL_Delay(2);
	HAL_GPIO_WritePin(shutPort, shutPin, GPIO_PIN_SET);

	dbg_printf("Checking boot state\n");
	while(tofBootState == 0) {
		status = VL53L1X_BootState(dev, &tofBootState);
		Timeout++;
		if (Timeout >= 200) {
			dbg_printf("Sensor not booting\n");
			Error_Handler();
			}
		HAL_Delay(2);
		}
	dbg_printf("Sensor booted\n");

	/* Initialize sensor */
	status = VL53L1X_SensorInit(dev);
	dbg_printf("Sensor initialization status: 0x%x\n", status);
	if (dev != newDev) {
		dbg_printf("Changing address to 0x%x\n", newDev);
		status = VL53L1X_SetI2CAddress(dev, newDev);
		dbg_printf("Set I2C Address status: 0x%x\n", status);
		}
	HAL_Delay(10);

	/* Modify default configurations */
	status = VL53L1X_SetDistanceMode(newDev, 1);
	dbg_printf("Set Distance Mode status: 0x%x\n", status);
	status = VL53L1X_SetTimingBudgetInMs(newDev, 20);
	dbg_printf("Set timing budget status: 0x%x\n", status);
	status = VL53L1X_SetInterMeasurementInMs(newDev, 20);
	dbg_printf("Set InterMeasurement status: 0x%x\n", status);
	//status = VL53L1X_SetOffset(tof1, 0);
	dbg_printf("Sensor routine done\n");
	return;
}

